CREATE OR REPLACE TABLE SUPPLYCHAINIQ_COCO.RAW.RAW_DATACO AS
SELECT
    TRY_CAST(ORDER_ITEM_ID AS NUMBER)                    AS ORDER_ITEM_ID,
    TRY_CAST(ORDER_ID AS NUMBER)                         AS ORDER_ID,
    TRY_CAST(ORDER_CUSTOMER_ID AS NUMBER)                AS CUSTOMER_ID,
    TRY_CAST(PRODUCT_CARD_ID AS NUMBER)                  AS PRODUCT_CARD_ID,
    TRY_CAST(PRODUCT_CATEGORY_ID AS NUMBER)              AS PRODUCT_CATEGORY_ID,
    TRIM(TYPE)                                           AS ORDER_TYPE,
    TRY_TO_DATE(ORDER_DATE, 'MM/DD/YYYY HH24:MI')       AS ORDER_DATE,
    TRY_TO_DATE(SHIPPING_DATE, 'MM/DD/YYYY HH24:MI')    AS SHIPPING_DATE,
    TRIM(DELIVERY_STATUS)                                AS DELIVERY_STATUS,
    TRY_CAST(LATE_DELIVERY_RISK AS NUMBER)               AS LATE_DELIVERY_RISK,
    TRY_CAST(DAYS_FOR_SHIPPING_REAL AS FLOAT)            AS DAYS_FOR_SHIPPING_REAL,
    TRY_CAST(DAYS_FOR_SHIPMENT_SCHEDULED AS FLOAT)       AS DAYS_FOR_SHIPMENT_SCHEDULED,
    TRY_CAST(ORDER_ITEM_QUANTITY AS NUMBER)              AS ORDER_ITEM_QUANTITY,
    TRY_CAST(SALES AS FLOAT)                             AS SALES,
    TRY_CAST(ORDER_ITEM_PRODUCT_PRICE AS FLOAT)          AS ORDER_ITEM_PRODUCT_PRICE,
    TRY_CAST(ORDER_ITEM_DISCOUNT AS FLOAT)               AS ORDER_ITEM_DISCOUNT,
    TRY_CAST(ORDER_ITEM_DISCOUNT_RATE AS FLOAT)          AS ORDER_ITEM_DISCOUNT_RATE,
    TRY_CAST(ORDER_ITEM_TOTAL AS FLOAT)                  AS ORDER_ITEM_TOTAL,
    TRY_CAST(ORDER_PROFIT_PER_ORDER AS FLOAT)            AS ORDER_PROFIT_PER_ORDER,
    TRY_CAST(ORDER_ITEM_PROFIT_RATIO AS FLOAT)           AS ORDER_ITEM_PROFIT_RATIO,
    TRY_CAST(BENEFIT_PER_ORDER AS FLOAT)                 AS BENEFIT_PER_ORDER,
    TRY_CAST(SALES_PER_CUSTOMER AS FLOAT)                AS SALES_PER_CUSTOMER,
    TRIM(ORDER_STATUS)                                   AS ORDER_STATUS,
    TRIM(SHIPPING_MODE)                                  AS SHIPPING_MODE,
    TRIM(CUSTOMER_FNAME)                                 AS CUSTOMER_FNAME,
    TRIM(CUSTOMER_LNAME)                                 AS CUSTOMER_LNAME,
    TRIM(CUSTOMER_EMAIL)                                 AS CUSTOMER_EMAIL,
    TRIM(CUSTOMER_SEGMENT)                               AS CUSTOMER_SEGMENT,
    TRIM(CUSTOMER_CITY)                                  AS CUSTOMER_CITY,
    TRIM(CUSTOMER_STATE)                                 AS CUSTOMER_STATE,
    TRIM(CUSTOMER_COUNTRY)                               AS CUSTOMER_COUNTRY,
    TRIM(CUSTOMER_ZIPCODE)                               AS CUSTOMER_ZIPCODE,
    TRIM(CUSTOMER_STREET)                                AS CUSTOMER_STREET,
    TRIM(CUSTOMER_PASSWORD)                              AS CUSTOMER_PASSWORD,
    TRIM(ORDER_COUNTRY)                                  AS ORDER_COUNTRY,
    TRIM(ORDER_REGION)                                   AS ORDER_REGION,
    TRIM(ORDER_STATE)                                    AS ORDER_STATE,
    TRIM(ORDER_CITY)                                     AS ORDER_CITY,
    TRIM(ORDER_ZIPCODE)                                  AS ORDER_ZIPCODE,
    TRIM(MARKET)                                         AS MARKET,
    TRY_CAST(LATITUDE AS FLOAT)                          AS LATITUDE,
    TRY_CAST(LONGITUDE AS FLOAT)                         AS LONGITUDE,
    TRY_CAST(DEPARTMENT_ID AS NUMBER)                    AS DEPARTMENT_ID,
    TRIM(DEPARTMENT_NAME)                                AS DEPARTMENT_NAME,
    TRY_CAST(CATEGORY_ID AS NUMBER)                      AS CATEGORY_ID,
    TRIM(CATEGORY_NAME)                                  AS CATEGORY_NAME,
    TRIM(PRODUCT_NAME)                                   AS PRODUCT_NAME,
    TRY_CAST(PRODUCT_PRICE AS FLOAT)                     AS PRODUCT_PRICE,
    TRIM(PRODUCT_STATUS)                                 AS PRODUCT_STATUS,
    TRIM(PRODUCT_DESCRIPTION)                            AS PRODUCT_DESCRIPTION,
    TRIM(PRODUCT_IMAGE)                                  AS PRODUCT_IMAGE
FROM SUPPLYCHAINIQ.RAW.RAW_DATACO;
