-- Evaluation schema setup for SUPPLYCHAINIQ_COCO
-- Run this to create all evaluation tables and views

-- Smoke test definitions
CREATE OR REPLACE TABLE SUPPLYCHAINIQ_COCO.EVALUATION.SEMANTIC_SMOKE_TESTS (
    TEST_ID VARCHAR, TEST_NAME VARCHAR, SQL_TEXT VARCHAR, EXPECTED_VALUE VARCHAR
);

-- Smoke test results
CREATE OR REPLACE TABLE SUPPLYCHAINIQ_COCO.EVALUATION.SEMANTIC_SMOKE_RESULTS (
    TEST_ID VARCHAR, RUN_ID VARCHAR, EXPECTED_VALUE VARCHAR, ACTUAL_VALUE VARCHAR,
    PASS_FLAG BOOLEAN, TESTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Agent benchmark definitions
CREATE OR REPLACE TABLE SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK (
    TEST_ID VARCHAR, CATEGORY VARCHAR, QUESTION VARCHAR,
    EXPECTED_BEHAVIOR VARCHAR, EXPECTED_SCOPE VARCHAR,
    PASS_CRITERIA VARCHAR, GOLD_SQL VARCHAR, ACTIVE BOOLEAN DEFAULT TRUE
);

-- Agent benchmark run metadata
CREATE OR REPLACE TABLE SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RUNS (
    RUN_ID VARCHAR, RUN_TS TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    MODEL_VERSION VARCHAR, NOTES VARCHAR
);

-- Agent benchmark results per question per run
CREATE OR REPLACE TABLE SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS (
    RUN_ID VARCHAR, TEST_ID VARCHAR, CATEGORY VARCHAR, QUESTION VARCHAR,
    EXPECTED_BEHAVIOR VARCHAR, ACTUAL_RESPONSE VARCHAR, ACTUAL_SQL VARCHAR,
    PASS_FLAG BOOLEAN, EVALUATOR_TYPE VARCHAR, EVALUATION_NOTE VARCHAR,
    EVALUATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Evaluation summary views
CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.SMOKE_TEST_SUMMARY AS
SELECT RUN_ID, COUNT(*) AS TESTS_EXECUTED, COUNT_IF(PASS_FLAG) AS TESTS_PASSED,
    COUNT_IF(NOT PASS_FLAG) AS TESTS_FAILED,
    ROUND(100.0 * COUNT_IF(PASS_FLAG) / NULLIF(COUNT(*), 0), 2) AS PASS_RATE_PCT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.SEMANTIC_SMOKE_RESULTS GROUP BY RUN_ID;

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_SUMMARY AS
SELECT RUN_ID, CATEGORY, COUNT(*) AS TESTS_EXECUTED, COUNT_IF(PASS_FLAG) AS TESTS_PASSED,
    COUNT_IF(NOT PASS_FLAG) AS TESTS_FAILED,
    ROUND(100.0 * COUNT_IF(PASS_FLAG) / NULLIF(COUNT(*), 0), 2) AS PASS_RATE_PCT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS GROUP BY RUN_ID, CATEGORY;

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_DETAIL AS
SELECT b.TEST_ID, b.CATEGORY, b.QUESTION, b.EXPECTED_BEHAVIOR, b.EXPECTED_SCOPE, b.PASS_CRITERIA,
    r.RUN_ID, r.ACTUAL_RESPONSE, r.ACTUAL_SQL, r.PASS_FLAG, r.EVALUATOR_TYPE, r.EVALUATION_NOTE, r.EVALUATED_AT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK b
LEFT JOIN SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS r ON b.TEST_ID = r.TEST_ID;

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.GOVERNANCE_SCORECARD AS
SELECT 'GOVERNANCE' AS CONTROL, COUNT(*) AS TESTS_EXECUTED, COUNT_IF(PASS_FLAG) AS TESTS_PASSED,
    COUNT_IF(NOT PASS_FLAG) AS TESTS_FAILED,
    ROUND(100.0 * COUNT_IF(PASS_FLAG) / NULLIF(COUNT(*), 0), 2) AS PASS_RATE_PCT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS WHERE CATEGORY IN ('GOVERNANCE','BOUNDARY');
