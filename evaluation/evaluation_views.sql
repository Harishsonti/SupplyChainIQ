-- Evaluation Views
-- Summary and detail views over smoke test and agent benchmark results

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.SMOKE_TEST_SUMMARY AS
SELECT RUN_ID, COUNT(*) AS TESTS_EXECUTED, COUNT_IF(PASS_FLAG) AS TESTS_PASSED,
    COUNT_IF(NOT PASS_FLAG) AS TESTS_FAILED,
    ROUND(100.0 * COUNT_IF(PASS_FLAG) / NULLIF(COUNT(*), 0), 2) AS PASS_RATE_PCT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.SEMANTIC_SMOKE_RESULTS GROUP BY RUN_ID;

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_SUMMARY AS
SELECT RUN_ID, CATEGORY, COUNT(*) AS TESTS_EXECUTED, COUNT_IF(PASS_FLAG) AS TESTS_PASSED,
    COUNT_IF(NOT PASS_FLAG) AS TESTS_FAILED,
    ROUND(100.0 * COUNT_IF(PASS_FLAG) / NULLIF(COUNT(*), 0), 2) AS PASS_RATE_PCT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS GROUP BY RUN_ID, CATEGORY;

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_DETAIL AS
SELECT b.TEST_ID, b.CATEGORY, b.QUESTION, b.EXPECTED_BEHAVIOR, b.EXPECTED_SCOPE, b.PASS_CRITERIA,
    r.RUN_ID, r.ACTUAL_RESPONSE, r.ACTUAL_SQL, r.PASS_FLAG, r.EVALUATOR_TYPE, r.EVALUATION_NOTE, r.EVALUATED_AT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK b
LEFT JOIN SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS r ON b.TEST_ID = r.TEST_ID;

CREATE OR REPLACE VIEW SUPPLYCHAINIQ_COCO.EVALUATION.GOVERNANCE_SCORECARD AS
SELECT 'GOVERNANCE' AS CONTROL, COUNT(*) AS TESTS_EXECUTED, COUNT_IF(PASS_FLAG) AS TESTS_PASSED,
    COUNT_IF(NOT PASS_FLAG) AS TESTS_FAILED,
    ROUND(100.0 * COUNT_IF(PASS_FLAG) / NULLIF(COUNT(*), 0), 2) AS PASS_RATE_PCT
FROM SUPPLYCHAINIQ_COCO.EVALUATION.AGENT_BENCHMARK_RESULTS WHERE CATEGORY IN ('GOVERNANCE','BOUNDARY');
